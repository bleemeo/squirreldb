// Package authtest generates certificates for the TLS tests.
package authtest

import (
	"crypto/ecdsa"
	"crypto/elliptic"
	"crypto/rand"
	"crypto/tls"
	"crypto/x509"
	"crypto/x509/pkix"
	"encoding/pem"
	"math/big"
	"net"
	"os"
	"path/filepath"
	"testing"
	"time"
)

// Certificates are the paths of PEM files generated by WriteCertificates.
type Certificates struct {
	// CAFile is a self-signed CA, which signed the server and client certificates.
	CAFile string
	// ServerCertFile and ServerKeyFile are valid for localhost and 127.0.0.1.
	ServerCertFile string
	ServerKeyFile  string
	ClientCertFile string
	ClientKeyFile  string
	// OtherKeyFile is a key that doesn't match any certificate.
	OtherKeyFile string
}

// WriteCertificates generates a CA, a server and a client certificate in dir.
func WriteCertificates(t *testing.T, dir string) Certificates {
	t.Helper()

	certs := Certificates{
		CAFile:         filepath.Join(dir, "ca.pem"),
		ServerCertFile: filepath.Join(dir, "server.pem"),
		ServerKeyFile:  filepath.Join(dir, "server-key.pem"),
		ClientCertFile: filepath.Join(dir, "client.pem"),
		ClientKeyFile:  filepath.Join(dir, "client-key.pem"),
		OtherKeyFile:   filepath.Join(dir, "other-key.pem"),
	}

	caKey := newKey(t, certs.CAFile+".key")
	caTemplate := &x509.Certificate{
		SerialNumber:          big.NewInt(1),
		Subject:               pkix.Name{CommonName: "SquirrelDB test CA"},
		NotBefore:             time.Now().Add(-time.Hour),
		NotAfter:              time.Now().Add(time.Hour),
		IsCA:                  true,
		BasicConstraintsValid: true,
		KeyUsage:              x509.KeyUsageCertSign,
	}
	caCert := writeCert(t, certs.CAFile, caTemplate, caTemplate, caKey, caKey)

	serverTemplate := &x509.Certificate{
		SerialNumber: big.NewInt(2),
		Subject:      pkix.Name{CommonName: "localhost"},
		NotBefore:    time.Now().Add(-time.Hour),
		NotAfter:     time.Now().Add(time.Hour),
		DNSNames:     []string{"localhost"},
		IPAddresses:  []net.IP{net.IPv4(127, 0, 0, 1), net.IPv6loopback},
		KeyUsage:     x509.KeyUsageDigitalSignature,
		ExtKeyUsage:  []x509.ExtKeyUsage{x509.ExtKeyUsageServerAuth},
	}
	writeCert(t, certs.ServerCertFile, serverTemplate, caCert, newKey(t, certs.ServerKeyFile), caKey)

	clientTemplate := &x509.Certificate{
		SerialNumber: big.NewInt(3),
		Subject:      pkix.Name{CommonName: "client"},
		NotBefore:    time.Now().Add(-time.Hour),
		NotAfter:     time.Now().Add(time.Hour),
		KeyUsage:     x509.KeyUsageDigitalSignature,
		ExtKeyUsage:  []x509.ExtKeyUsage{x509.ExtKeyUsageClientAuth},
	}
	writeCert(t, certs.ClientCertFile, clientTemplate, caCert, newKey(t, certs.ClientKeyFile), caKey)

	newKey(t, certs.OtherKeyFile)

	return certs
}

// ClientConfig returns a client TLS config trusting the CA, with the client
// certificate when withClientCert is true.
func (c Certificates) ClientConfig(t *testing.T, withClientCert bool) *tls.Config {
	t.Helper()

	caPEM, err := os.ReadFile(c.CAFile)
	if err != nil {
		t.Fatal(err)
	}

	pool := x509.NewCertPool()
	pool.AppendCertsFromPEM(caPEM)

	cfg := &tls.Config{RootCAs: pool, MinVersion: tls.VersionTLS12}

	if withClientCert {
		cert, err := tls.LoadX509KeyPair(c.ClientCertFile, c.ClientKeyFile)
		if err != nil {
			t.Fatal(err)
		}

		cfg.Certificates = []tls.Certificate{cert}
	}

	return cfg
}

func newKey(t *testing.T, path string) *ecdsa.PrivateKey {
	t.Helper()

	key, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		t.Fatal(err)
	}

	der, err := x509.MarshalECPrivateKey(key)
	if err != nil {
		t.Fatal(err)
	}

	writePEM(t, path, "EC PRIVATE KEY", der)

	return key
}

func writeCert(
	t *testing.T,
	path string,
	template, parent *x509.Certificate,
	key, parentKey *ecdsa.PrivateKey,
) *x509.Certificate {
	t.Helper()

	der, err := x509.CreateCertificate(rand.Reader, template, parent, &key.PublicKey, parentKey)
	if err != nil {
		t.Fatal(err)
	}

	writePEM(t, path, "CERTIFICATE", der)

	cert, err := x509.ParseCertificate(der)
	if err != nil {
		t.Fatal(err)
	}

	return cert
}

func writePEM(t *testing.T, path, blockType string, der []byte) {
	t.Helper()

	if err := os.WriteFile(path, pem.EncodeToMemory(&pem.Block{Type: blockType, Bytes: der}), 0o600); err != nil {
		t.Fatal(err)
	}
}
